# Actions
# ---------------------------------------------------------------------------

def _write_manifest(staged: Path, name: str, marker: str = INSTALLER_MARKER) -> None:
    files: dict[str, str] = {}
    for path, is_dir in _iter_entries(staged):
        if is_dir:
            continue
        rel = path.relative_to(staged).as_posix()
        if rel == MANIFEST_NAME:
            continue
        if _runtime_cache(rel):
            continue
        files[rel] = _sha256(path)
    manifest = {
        "installer": marker,
        "skill": name,
        "files": files,
    }
    (staged / MANIFEST_NAME).write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _preview(
    scope: Path, target: Path, *, marker: str = INSTALLER_MARKER,
    collision_on_modified: bool = False,
) -> dict:
    _check_target_safe(scope, target)
    if target.is_symlink() or target.exists():
        if not target.is_dir() or target.is_symlink():
            raise Reject(f"target exists and is not a plain directory: {target}",
                         collision=True)
        _verify_owned(target, marker, collision_on_modified=collision_on_modified)
        outcome = "update"
    else:
        outcome = "install"
    return {"action": "preview", "target": str(target), "outcome": outcome}


def _install(
    source: Path, scope: Path, target: Path, name: str,
    *, marker: str = INSTALLER_MARKER, collision_on_modified: bool = False,
    host: str = "Codex",
) -> dict:
    _check_target_safe(scope, target)
    updating = target.exists()
    if updating:
        if target.is_symlink() or not target.is_dir():
            raise Reject(f"target exists and is not a plain directory: {target}",
                         collision=True)
        _verify_owned(target, marker, collision_on_modified=collision_on_modified)
    skills_dir = target.parent
    stage = skills_dir / f".{name}.cld-stage-{os.getpid()}"
    backup = skills_dir / f".{name}.cld-backup-{os.getpid()}"
    if stage.exists() or backup.exists() or stage.is_symlink() or backup.is_symlink():
        raise Reject("stale staging/backup directory present; refusing to proceed")
    _check_target_safe(scope, stage)
    _check_target_safe(scope, backup)
    try:
        try:
            skills_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise Reject(f"cannot create {skills_dir}: {exc}") from exc
        shutil.copytree(source, stage, symlinks=False,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        _write_manifest(stage, name, marker)
        renamed = False
        copied = False
        try:
            if updating:
                target.replace(backup)
                renamed = True
            try:
                stage.replace(target)
            except OSError as publish_exc:
                if renamed:
                    # Roll back immediately; updates must never copy into the
                    # target. Do not retry this restore in the outer handler.
                    renamed = False
                    try:
                        backup.replace(target)
                    except BaseException as restore_exc:
                        publish_exc.add_note(
                            f"could not restore {target}: {restore_exc}; "
                            f"previous install retained at {backup}")
                        raise publish_exc
                    raise Reject(
                        "update could not be published because the skills "
                        "folder is in use; the previous installation was kept. "
                        f"Close running {host} sessions and retry."
                    ) from publish_exc
                # Watched skills folders on Windows can deny the rename.
                # Claim the directory exclusively before copying. A failed
                # mkdir means another process owns it; never clean it up.
                target.mkdir()
                copied = True
                shutil.copytree(stage, target, symlinks=False, dirs_exist_ok=True)
                _verify_owned(target, marker, collision_on_modified=collision_on_modified)
                shutil.rmtree(stage)
        except BaseException as exc:
            if copied:
                try:
                    _check_target_safe(scope, target)
                    # Exclusive mkdir claims the directory, not files another
                    # process may subsequently add. On a fresh install retain
                    # such contents in place; there is no backup to restore.
                    foreign_entries = not renamed and any(
                        not (stage / path.relative_to(target)).exists()
                        for path, _is_dir in _iter_entries(target)
                    )
                    if foreign_entries:
                        exc.add_note(
                            f"target contains entries absent from the stage; "
                            f"retained at {target} to preserve foreign contents")
                    else:
                        shutil.rmtree(target)
                except BaseException as cleanup_exc:
                    # A locked partial copy must not block restoring the old
                    # install. Retain it under a vacant sibling for inspection.
                    failed = skills_dir / f".{name}.cld-failed-{os.getpid()}"
                    try:
                        suffix = 0
                        while failed.exists() or failed.is_symlink():
                            suffix += 1
                            failed = skills_dir / (
                                f".{name}.cld-failed-{os.getpid()}-{suffix}")
                        _check_target_safe(scope, failed)
                        target.rename(failed)
                    except BaseException as move_exc:
                        exc.add_note(
                            f"failed target cleanup at {target}: {cleanup_exc}; "
                            f"could not retain it at {failed}: {move_exc}")
                    else:
                        exc.add_note(
                            f"failed target cleanup: {cleanup_exc}; "
                            f"partial install retained at {failed}")
            # Publish failed: restore the previous installation if we moved it.
            if renamed:
                try:
                    if target.exists() or target.is_symlink():
                        raise FileExistsError(f"target is occupied: {target}")
                    backup.replace(target)
                except BaseException as restore_exc:
                    exc.add_note(
                        f"could not restore {target}: {restore_exc}; "
                        f"previous install retained at {backup}")
            raise
        cleanup_warning = None
        if renamed:
            try:
                _check_target_safe(scope, backup)
                _verify_owned(backup, marker, collision_on_modified=collision_on_modified)
                shutil.rmtree(backup)
            except (OSError, Reject) as exc:
                # The new target is already published. Report success and keep
                # the old backup for manual inspection rather than claiming a
                # failed operation left the previous target untouched.
                cleanup_warning = f"old backup retained at {backup}: {exc}"
    except BaseException as exc:
        try:
            if stage.is_dir() and not stage.is_symlink():
                _check_target_safe(scope, stage)
                shutil.rmtree(stage)
        except BaseException as cleanup_exc:
            exc.add_note(
                f"could not clean staging directory; retained at {stage}: "
                f"{cleanup_exc}")
        raise
    outcome = "updated" if updating else "installed"
    result = {"action": "install", "target": str(target), "outcome": outcome}
    if cleanup_warning:
        result["cleanup_warning"] = cleanup_warning
    return result


def _uninstall(
    scope: Path, target: Path, name: str, *, marker: str = INSTALLER_MARKER,
    collision_on_modified: bool = False,
) -> dict:
    _check_target_safe(scope, target)
    if target.is_symlink():
        raise Reject(f"target is a symlink: {target}")
    if not target.exists():
        raise Reject(f"nothing to uninstall: {target} does not exist")
    if not target.is_dir():
        raise Reject(f"target is not a directory: {target}", collision=True)
    _verify_owned(target, marker, collision_on_modified=collision_on_modified)
    shutil.rmtree(target)
    return {"action": "uninstall", "target": str(target), "outcome": "uninstalled"}


